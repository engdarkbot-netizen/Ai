package sa.bidengine.model;

/**
 * مستند إلزامي تطلبه الكراسة (شهادة، ضمان، سجل...) — غيابه عن العرض سبب استبعاد.
 * حائط الهلوسة يسري هنا أيضاً: مستند بلا اقتباس حرفي من الكراسة = مستند مرفوض.
 */
public record MandatoryDocument(
        String name,        // اسم المستند كما تطلبه الكراسة
        String sourceQuote, // اقتباس حرفي من الكراسة يثبت الطلب
        int sourcePage      // رقم الصفحة التقريبي (من ترويسة المقطع)
) {}
