package sa.bidengine.model;

/**
 * معيار تقييم وزنه معروف — هذه المعايير هي التي "تكتب" العرض الفائز لاحقاً.
 * حائط الهلوسة يسري هنا أيضاً: معيار بلا اقتباس حرفي من الكراسة = معيار مرفوض.
 */
public record EvaluationCriterion(
        String name,        // اسم المعيار (مثال: الخبرات السابقة، خطة العمل...)
        String weight,      // الوزن كما ورد (نص: "30%" أو "30 درجة") — لا تحوّله رقماً الآن
        String notes,       // أي تفاصيل وردت عن طريقة التقييم
        String sourceQuote, // اقتباس حرفي من الكراسة يثبت المعيار
        int sourcePage      // رقم الصفحة التقريبي (من ترويسة المقطع)
) {}
