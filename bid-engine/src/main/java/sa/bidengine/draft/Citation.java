package sa.bidengine.draft;

/**
 * اقتباس حرفي من مقطع في قاعدة معرفة العميل يسند ادعاءً في فقرة من العرض.
 * حائط الهلوسة يسري هنا ميكانيكياً: الاقتباس لا يُقبل إلا بعد التحقق برمجياً
 * أنه موجود فعلاً في نص المقطع المشار إليه (بعد تطبيع المسافات) — انظر SectionWriter.
 */
public record Citation(
        String chunkId,   // معرف المقطع في kb-index.json (مثال: KB-0001)
        String source,    // اسم ملف وثيقة العميل — يُملأ من المقطع نفسه لا من النموذج
        int page,         // رقم الصفحة (0 لملفات txt/md) — يُملأ من المقطع نفسه
        String quote      // الاقتباس الحرفي كما ورد في نص المقطع
) {}
